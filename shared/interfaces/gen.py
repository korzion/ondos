"""Generate code from the interface sources in shared/interfaces/.

Sources (edit these, never the generated files):
  topics.json, variables.json, constants.json, schemas/*.schema.json, packets/*.json

Generated:
  shared/topics.py                          topic names, enums, constants (Python)
  shared/topics.ts                          the same for TypeScript
  shared/interfaces/schemas.bundle.json     all schemas in one file (used by bus.ts)
  shared/protocol/packets.py                IF-01 / IF-02 packet pack/unpack (Python)
  shared/firmware/include/ondos_packets.h   IF-01 / IF-02 packet structs (C++)

Usage:
  python shared/interfaces/gen.py           write the files
  python shared/interfaces/gen.py --check   fail if a generated file is out of date (CI)
"""
from __future__ import annotations

import json
import pprint
import re
import struct
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SHARED = HERE.parent
HEADER = "AUTO-GENERATED by shared/interfaces/gen.py from shared/interfaces/. Do not edit."


def load(name: str):
    return json.loads((HERE / name).read_text(encoding="utf-8"))


def ident(topic: str) -> str:
    return re.sub(r"[^A-Za-z0-9]+", "_", topic).strip("_").upper()


def snake_upper(name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).upper()


def camel(name: str) -> str:
    return "".join(p.capitalize() for p in name.split("_"))


# ------------------------------------------------------------------ sources
topics = load("topics.json")["topics"]
variables = load("variables.json")["keys"]
constants = {k: v["value"] for k, v in load("constants.json")["constants"].items()}
schemas = {p.name: json.loads(p.read_text(encoding="utf-8")) for p in sorted((HERE / "schemas").glob("*.schema.json"))}
enums = {name: d["enum"] for name, d in schemas["common.schema.json"]["$defs"].items() if "enum" in d}
codes = load("packets/codes.json")["tables"]
packet_files = [load(f"packets/{n}") for n in ("if01_espnow.json", "if02_serial.json")]


def check_sources() -> None:
    errors = []
    for t in topics:
        if t["schema"] and t["schema"] not in schemas:
            errors.append(f"{t['name']}: schema {t['schema']} not found")
        if not t["name"].startswith("{") and t["writer"] not in enums["writer"] and "{" not in t["writer"]:
            errors.append(f"{t['name']}: unknown writer {t['writer']}")
    if set(variables) != set(enums["config_key"]):
        errors.append("variables.json keys differ from config_key enum")
    for key, v in variables.items():
        if v["owner"] not in enums["writer"]:
            errors.append(f"variables.json {key}: unknown owner {v['owner']}")
    for tname, table in codes.items():
        if table["enum"]:
            missing = set(enums[table["enum"]]) - set(table["codes"])
            if missing:
                errors.append(f"codes.json {tname}: no code for {sorted(missing)}")
        if len(set(table["codes"].values())) != len(table["codes"]):
            errors.append(f"codes.json {tname}: duplicate codes")
    for pf in packet_files:
        seen = set()
        for p in pf["packets"]:
            if p["msg_type"] in seen:
                errors.append(f"{pf['link']}: duplicate msg_type {p['msg_type']}")
            seen.add(p["msg_type"])
            for _, ftype in p["fields"]:
                if ftype.startswith("enum:") and ftype[5:] not in codes:
                    errors.append(f"{p['name']}: unknown code table {ftype}")
    if errors:
        sys.exit("interface sources are inconsistent:\n  " + "\n  ".join(errors))


# ------------------------------------------------------------------ topics.py
def gen_topics_py() -> str:
    out = [f'"""{HEADER}\n\nTopic names, enums and fixed constants of the Ondos bus (IF-03).\nNobody types a topic string by hand: import it from here."""', "",
           "from __future__ import annotations", "", "# ---- topics"]
    for t in topics:
        if "{" in t["name"]:
            continue
        out.append(f'{ident(t["name"])} = "{t["name"]}"')
    out += ["", "",
            "def cs_variables(key: str) -> str:", '    """cs/variables/<key> (IF-07)"""', "    _check_key(key)", '    return f"cs/variables/{key}"', "", "",
            "def variables_spec(key: str) -> str:", '    """<key>/variables_spec (IF-07)"""', "    _check_key(key)", '    return f"{key}/variables_spec"', "", "",
            "def sys_online(program: str) -> str:", '    """sys/online/<program> (IF-03)"""',
            "    if program not in WRITER_VALUES:", '        raise ValueError(f"unknown program {program!r}")', '    return f"sys/online/{program}"', "", "",
            "def _check_key(key: str) -> None:", "    if key not in CONFIG_KEY_VALUES:", '        raise ValueError(f"unknown config key {key!r}")', "", "",
            "# ---- enums (schemas/common.schema.json)"]
    for name, values in enums.items():
        out.append(f"{name.upper()}_VALUES = {tuple(values)!r}")
    out += ["", "# ---- configuration keys and variable names (variables.json)",
            f"VARIABLES = {json.dumps({k: v['names'] for k, v in variables.items()}, indent=4)}",
            f"KEY_OWNER = {json.dumps({k: v['owner'] for k, v in variables.items()}, indent=4)}",
            "", "# ---- fixed constants (constants.json)"]
    for k, v in constants.items():
        out.append(f"{k} = {v!r}")
    out += ["", "# ---- topic table (topics.json)", "TOPIC_TABLE = " + pprint.pformat(topics, sort_dicts=False, width=110), "", "",
            "def topic_info(topic: str) -> dict:",
            '    """Registry entry for a concrete topic name, with writer resolved for patterns."""',
            "    parts = topic.split('/')",
            "    for t in TOPIC_TABLE:",
            "        pat = t['name'].split('/')",
            "        if len(pat) != len(parts):",
            "            continue",
            "        params = {}",
            "        for p, v in zip(pat, parts):",
            "            if p.startswith('{'):",
            "                params[p[1:-1]] = v",
            "            elif p != v:",
            "                break",
            "        else:",
            "            if 'key' in params and params['key'] not in CONFIG_KEY_VALUES:",
            "                continue",
            "            if 'program' in params and params['program'] not in WRITER_VALUES:",
            "                continue",
            "            info = dict(t, topic=topic, params=params)",
            "            if t['writer'] == '{owner of key}':",
            "                info['writer'] = KEY_OWNER[params['key']]",
            "            elif t['writer'] == '{program}':",
            "                info['writer'] = params['program']",
            "            return info",
            '    raise KeyError(f"unknown topic {topic!r}")', ""]
    return "\n".join(out)


# ------------------------------------------------------------------ topics.ts
def gen_topics_ts() -> str:
    out = [f"// {HEADER}", "// Topic names, enums and fixed constants of the Ondos bus (IF-03).", "// Nobody types a topic string by hand: import it from here.", "", "// ---- topics"]
    for t in topics:
        if "{" in t["name"]:
            continue
        out.append(f'export const {ident(t["name"])} = "{t["name"]}" as const;')
    out += ["", "// ---- enums (schemas/common.schema.json)"]
    for name, values in enums.items():
        out.append(f"export const {name.upper()}_VALUES = {json.dumps(values)} as const;")
        out.append(f"export type {camel(name)} = (typeof {name.upper()}_VALUES)[number];")
    out += ["",
            "export function csVariables(key: ConfigKey): string { return `cs/variables/${key}`; }",
            "export function variablesSpec(key: ConfigKey): string { return `${key}/variables_spec`; }",
            "export function sysOnline(program: Writer): string { return `sys/online/${program}`; }",
            "", "// ---- configuration keys and variable names (variables.json)",
            f"export const VARIABLES: Record<ConfigKey, readonly string[]> = {json.dumps({k: v['names'] for k, v in variables.items()}, indent=2)};",
            f"export const KEY_OWNER: Record<ConfigKey, Writer> = {json.dumps({k: v['owner'] for k, v in variables.items()}, indent=2)};",
            "", "// ---- fixed constants (constants.json)"]
    for k, v in constants.items():
        out.append(f"export const {k} = {json.dumps(v)};")
    out += ["", "// ---- topic table (topics.json)",
            "export interface TopicEntry { name: string; interface: string; writer: string; retained: boolean; qos: 0 | 1; payload: \"json\" | \"jpeg\" | \"bool\"; schema: string | null; version: number | null; rate: string; }",
            "export interface TopicInfo extends TopicEntry { topic: string; params: Record<string, string>; }",
            f"export const TOPIC_TABLE: readonly TopicEntry[] = {json.dumps(topics, indent=2)};",
            "",
            "/** Registry entry for a concrete topic name, with writer resolved for patterns. */",
            "export function topicInfo(topic: string): TopicInfo {",
            "  const parts = topic.split(\"/\");",
            "  for (const t of TOPIC_TABLE) {",
            "    const pat = t.name.split(\"/\");",
            "    if (pat.length !== parts.length) continue;",
            "    const params: Record<string, string> = {};",
            "    let ok = true;",
            "    pat.forEach((p, i) => { if (p.startsWith(\"{\")) params[p.slice(1, -1)] = parts[i]; else if (p !== parts[i]) ok = false; });",
            "    if (!ok) continue;",
            "    if (params.key !== undefined && !(CONFIG_KEY_VALUES as readonly string[]).includes(params.key)) continue;",
            "    if (params.program !== undefined && !(WRITER_VALUES as readonly string[]).includes(params.program)) continue;",
            "    let writer = t.writer;",
            "    if (writer === \"{owner of key}\") writer = KEY_OWNER[params.key as ConfigKey];",
            "    else if (writer === \"{program}\") writer = params.program;",
            "    return { ...t, writer, topic, params };",
            "  }",
            "  throw new Error(`unknown topic ${topic}`);",
            "}", ""]
    return "\n".join(out)


# ------------------------------------------------------------------ packets
CTYPE = {"u8": "uint8_t", "u16": "uint16_t", "u32": "uint32_t", "i8": "int8_t", "f32": "float", "bool": "uint8_t"}
STRUCT = {"u8": "B", "u16": "H", "u32": "I", "i8": "b", "f32": "f", "bool": "?"}


def base_type(ftype: str) -> str:
    return "u8" if ftype.startswith("enum:") else ftype


def gen_packets_h() -> str:
    out = [f"// {HEADER}", "// IF-01 (ESP-NOW) and IF-02 (serial) packets. STATUS: DRAFT until A and B confirm",
           "// shared/interfaces/packets/*.json. Packed, little endian, first byte = msg_type.",
           "#pragma once", "#include <stdint.h>", "", "namespace ondos {", ""]
    for tname, table in codes.items():
        out.append(f"// codes.json: {tname}{'' if table['from_doc'] else ' (draft)'}")
        out.append(f"enum class {camel(tname)} : uint8_t {{")
        for k, v in table["codes"].items():
            out.append(f"  {camel(k)} = {v},")
        out += ["};", ""]
    for k, v in constants.items():
        if isinstance(v, int) and k.endswith("_MS"):
            out.append(f"constexpr uint32_t {k} = {v};")
    out.append("")
    for pf in packet_files:
        ns = pf["link"]
        out.append(f"namespace {ns} {{")
        for p in pf["packets"]:
            out.append(f"constexpr uint8_t MSG_{snake_upper(p['name'])} = {p['msg_type']};")
        out.append("")
        for p in pf["packets"]:
            out.append(f"// {p['direction']}, {p['rate']}")
            out.append(f"struct __attribute__((packed)) {p['name']} {{")
            out.append(f"  uint8_t msg_type = MSG_{snake_upper(p['name'])};")
            for fname, ftype in p["fields"]:
                comment = f"  // {ftype[5:]} code" if ftype.startswith("enum:") else ("  // 0/1" if ftype == "bool" else "")
                out.append(f"  {CTYPE[base_type(ftype)]} {fname};{comment}")
            out.append("};")
            size = struct.calcsize("<B" + "".join(STRUCT[base_type(t)] for _, t in p["fields"]))
            out.append(f"static_assert(sizeof({p['name']}) == {size}, \"{p['name']} size\");")
            out.append("")
        out += [f"}}  // namespace {ns}", ""]
    out += ["}  // namespace ondos", ""]
    return "\n".join(out)


def gen_packets_py() -> str:
    out = [f'"""{HEADER}\n\nIF-01 (ESP-NOW) and IF-02 (serial) packets. STATUS: DRAFT until A and B confirm\nshared/interfaces/packets/*.json. Packed, little endian, first byte = msg_type.\nEnum fields are given and returned as their names (e.g. "glove"), bools as bool."""',
           "", "from __future__ import annotations", "", "import struct", ""]
    out.append(f"CODES = {json.dumps({k: v['codes'] for k, v in codes.items()}, indent=4)}")
    out.append("NAMES = {t: {v: k for k, v in c.items()} for t, c in CODES.items()}")
    out.append("")
    table = {}
    for pf in packet_files:
        for p in pf["packets"]:
            fmt = "<B" + "".join(STRUCT[base_type(t)] for _, t in p["fields"])
            table.setdefault(pf["link"], {})[p["name"]] = {
                "msg_type": p["msg_type"], "format": fmt,
                "fields": [[n, t[5:] if t.startswith("enum:") else None] for n, t in p["fields"]],
            }
    out.append("PACKETS = " + pprint.pformat(table, sort_dicts=False, width=110))
    out += ["", "",
            "def pack(link: str, name: str, fields: dict) -> bytes:",
            '    """Build the payload (msg_type first) of packet `name` on link "espnow" or "serial"."""',
            "    p = PACKETS[link][name]",
            "    values = [p['msg_type']]",
            "    for fname, code_table in p['fields']:",
            "        v = fields[fname]",
            "        values.append(CODES[code_table][v] if code_table else v)",
            "    return struct.pack(p['format'], *values)",
            "", "",
            "def unpack(link: str, payload: bytes) -> tuple[str, dict]:",
            '    """Decode a payload; returns (packet name, fields). Raises ValueError on an unknown type or size."""',
            "    if not payload:",
            "        raise ValueError('empty payload')",
            "    for name, p in PACKETS[link].items():",
            "        if p['msg_type'] == payload[0]:",
            "            if len(payload) != struct.calcsize(p['format']):",
            "                raise ValueError(f'{name}: wrong size {len(payload)}')",
            "            raw = struct.unpack(p['format'], payload)[1:]",
            "            return name, {f: (NAMES[c][v] if c else v) for (f, c), v in zip(p['fields'], raw)}",
            "    raise ValueError(f'unknown msg_type {payload[0]}')", ""]
    return "\n".join(out)


def gen_bundle() -> str:
    return json.dumps({"$comment": HEADER, "schemas": schemas}, indent=1, ensure_ascii=False) + "\n"


OUTPUTS = {
    SHARED / "topics.py": gen_topics_py,
    SHARED / "topics.ts": gen_topics_ts,
    HERE / "schemas.bundle.json": gen_bundle,
    SHARED / "protocol" / "packets.py": gen_packets_py,
    SHARED / "firmware" / "include" / "ondos_packets.h": gen_packets_h,
}


def main() -> int:
    check_sources()
    check = "--check" in sys.argv
    stale = []
    for path, fn in OUTPUTS.items():
        text = fn()
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(str(path.relative_to(SHARED.parent)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
            print("wrote", path.relative_to(SHARED.parent))
    if stale:
        print("out of date, run python shared/interfaces/gen.py:\n  " + "\n  ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
